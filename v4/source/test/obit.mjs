import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
import path from 'node:path';
const root = path.dirname(new URL(import.meta.url).pathname);
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
let prompts = [];
await page.exposeFunction('__logPrompt', p => prompts.push(p));
await page.addInitScript(() => {
  const fake = async (input, opts = {}) => {
    window.__logPrompt(String(input));
    await new Promise(r => setTimeout(r, 150));
    const text = 'RETRACTION NOTICE. The authors withdraw their claim that the cat was alive. Subsequent measurement, conducted by a bullet, was conclusive. We thank the reviewers, the box, and the cat, who did not consent to any of this.';
    opts.onText && opts.onText({ text: text.slice(0, 60), delta: text.slice(0, 60) });
    await new Promise(r => setTimeout(r, 150));
    opts.onText && opts.onText({ text, delta: text.slice(60) });
    return { text, truncated: false, modelTierApplied: 'default' };
  };
  window.claude = { use: async (n) => (n === 'sample' ? fake : null) };
});
await page.goto('file://' + path.join(root, 'harness.html'));
await page.waitForTimeout(1000);
await page.evaluate(() => { QCAT.debug.start(4); QCAT.Game.lives = 1; QCAT.debug.ff(4); const P = QCAT.Player; P.invuln = 0; P.measureHit(P.branches.slice(), 'bullet'); QCAT.debug.ff(4); });
await page.waitForTimeout(300);
const visible = await page.evaluate(() => ({ over: !document.getElementById('scr-over').hidden, row: !document.getElementById('obit-row').hidden }));
console.log('over screen + claude row visible:', JSON.stringify(visible));
await page.click('#b-obit');
await page.waitForTimeout(800);
const txt = await page.evaluate(() => ({ obit: document.getElementById('obit').textContent, note: document.getElementById('obit-note').textContent }));
console.log('obit now:', txt.obit.slice(0, 90) + '…', '| note:', txt.note);
console.log('prompt sent (head):', (prompts[0] || '').slice(0, 260).replace(/\n/g, ' '));
await page.click('#b-copy');
await page.waitForTimeout(300);
const share = await page.evaluate(() => ({ toast: document.getElementById('toast').textContent, share: document.getElementById('share-text').hidden ? '(hidden)' : document.getElementById('share-text').textContent }));
console.log('copy result:', JSON.stringify(share).slice(0, 200));
await page.screenshot({ path: path.join(root, 'shots', 'obit.png') });
console.log('ERRORS', errors.length ? errors : 'none');
await browser.close();
