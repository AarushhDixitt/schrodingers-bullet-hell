import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
import path from 'node:path';
const root = path.dirname(new URL(import.meta.url).pathname);
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 640, height: 400 } });
const errs = []; page.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
await page.goto('file://' + path.join(root, 'harness.html')); await page.waitForTimeout(700);
const r = await page.evaluate(() => {
  const { Game: G, Player: P, Input: I } = QCAT, out = {};
  QCAT.UI.start(1, 'arcade', { diff: 'graduate' }); QCAT.debug.god(); for (let i = 0; i < 30; i++) G.frame(1 / 60);
  P.coh = 100; P.splitCd = 0; P.split(); for (let i = 0; i < 30; i++) G.frame(1 / 60);
  const run = (n, keys) => { const x0 = P.x; for (let i = 0; i < n; i++) { for (const k of keys) I.down.add(k); G.frame(1 / 60); } return Math.round(P.x - x0); };
  P.x = 300; P.coh = 100; out.walk1s = run(60, ['KeyD']);
  P.x = 300; P.coh = 100; I.edges.add('dash'); out.sprint1s = run(60, ['KeyD', 'AltLeft']); out.cohAfterSprint = Math.round(P.coh); out.sprinting = P.sprinting;
  I.down.clear(); G.frame(1 / 60); out.stopped = !P.sprinting;
  for (let i = 0; i < 60; i++) G.frame(1 / 60);
  P.x = 300; P.coh = 100; I.edges.add('dash'); let x0 = P.x; for (let i = 0; i < 5; i++) { I.down.add('KeyD'); I.down.add('AltLeft'); G.frame(1 / 60); } I.down.delete('AltLeft'); for (let i = 0; i < 55; i++) { I.down.add('KeyD'); G.frame(1 / 60); } out.tap1s = Math.round(P.x - x0); out.cohAfterTap = Math.round(P.coh);
  I.down.clear(); return out;
});
console.log(JSON.stringify(r), errs.join(' | '));
await browser.close();
